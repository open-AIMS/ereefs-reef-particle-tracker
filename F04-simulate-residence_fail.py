def list_daily_subcubes(subcube_dir: Path, label_id: str, year: int) -> List[Path]:
	"""List daily subcube NetCDF files for a given reef-year.

	Expected layout produced by extraction stage:
	subcube_dir / LABEL_ID / YEAR / <name>_<LABEL_ID>_k<k>_YYYYMMDD.nc
	"""

	year_dir = subcube_dir / label_id / str(year)
	if not year_dir.exists():
		return []
	# Broad match then filter: we expect final underscore-separated token to be an 8-digit date YYYYMMDD
	candidates = list(year_dir.glob(f"*_{label_id}_k*_{year}*.nc"))
	results: List[Path] = []
	for p in candidates:
		stem = p.stem
		parts = stem.split("_")
		if not parts:
			continue
		date_token = parts[-1]
		if len(date_token) == 8 and date_token.isdigit() and date_token.startswith(str(year)):
			results.append(p)
	return sorted(results)
def available_day_index(files: List[Path]) -> dict[str, Path]:
	"""Map YYYYMMDD -> file Path for quick lookup."""

	index: dict[str, Path] = {}
	for f in files:
		# Extract trailing date stamp before extension
		stem = f.stem  # ..._YYYYMMDD
		parts = stem.split("_")
		if not parts:
			continue
		last = parts[-1]
		if len(last) == 8 and last.isdigit():
			index[last] = f
	return index


def verify_coverage(
	label_id: str,
	year: int,
	injection_times: List[np.datetime64],
	runtime_days: int,
	day_index: dict[str, Path],
) -> List[str]:
	"""Verify all required day files exist for each weekly injection.

	Returns a sorted list of missing YYYY-MM-DD strings (unique across weeks).
	"""

	missing: set[str] = set()
	for inj in injection_times:
		needed = required_day_strings(inj, runtime_days)
		for d in needed:
			ymd = d.replace("-", "")
			if ymd not in day_index:
				missing.add(d)
	return sorted(missing)


