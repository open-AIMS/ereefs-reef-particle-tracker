def weekly_injections(year: int, injection_hour: int) -> List[np.datetime64]:
	"""Return list of weekly injection datetimes starting 1 Jan of year.

	Each injection is at local (naive) hour every 7 days until year end.
	"""
	if not (0 <= injection_hour <= 23):
		raise ValueError("injection_hour must be between 0 and 23 inclusive")
	start = np.datetime64(f"{year}-01-01T{injection_hour:02d}:00:00")
	end_limit = np.datetime64(f"{year}-12-31T23:59:59")
	weeks: List[np.datetime64] = []
	current = start
	one_week = np.timedelta64(7, "D")
	while current <= end_limit:
		weeks.append(current)
		current = current + one_week
	return weeks

def required_day_strings(start: np.datetime64, runtime_days: int) -> List[str]:
	"""Return list of YYYY-MM-DD day strings needed from start for runtime.

	Includes the start day and all full subsequent days up to start + runtime_days.
	Example: runtime_days=21 returns 22 calendar days (0..21) to ensure coverage.
	"""

	days: List[str] = []
	base_day = start.astype("datetime64[D]")
	for d in range(runtime_days + 1):
		day = base_day + np.timedelta64(d, "D")
		days.append(str(day))
	return days


