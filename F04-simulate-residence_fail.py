def animate_week(pf_path: Path, reef_polygon: Polygon, out_path: Path, max_hours: float = 168.0):
	"""Create MP4 animation for first week using particle file outputs.

	Parameters
	----------
	pf_path : Path
		ParticleFile NetCDF path.
	reef_polygon : Polygon
		Reef outline for plotting.
	out_path : Path
		MP4 output path.
	max_hours : float
		Limit animation to this many hours from release (default 7 days).
	"""
	import matplotlib.pyplot as plt  # type: ignore
	from matplotlib import animation  # type: ignore
	ds = xr.open_dataset(pf_path)
	if "lon" not in ds or "lat" not in ds:
		logging.warning("Particle file missing lon/lat for animation")
		return
	lon = ds["lon"].values  # (obs, traj)
	lat = ds["lat"].values
	times = ds["time"].values
	base_time = np.datetime64(times[0])
	elapsed_hours = ((times - base_time).astype("timedelta64[s]").astype(float) / 3600.0)
	valid_frames = np.where(elapsed_hours <= max_hours)[0]
	if valid_frames.size == 0:
		logging.warning("No frames within max_hours for animation")
		return
	valid_frames = valid_frames.tolist()
	fig, ax = plt.subplots(figsize=(5, 5))
	minx, miny, maxx, maxy = reef_polygon.bounds
	padx = (maxx - minx) * 0.2
	pady = (maxy - miny) * 0.2
	ax.set_xlim(minx - padx, maxx + padx)
	ax.set_ylim(miny - pady, maxy + pady)
	reef_x, reef_y = reef_polygon.exterior.xy
	ax.plot(reef_x, reef_y, color='darkgreen', linewidth=1.2)
	scat = ax.scatter([], [], s=4, c='tab:blue')
	ax.set_title("Week animation")
	def init():  # noqa: D401
		scat.set_offsets(np.empty((0, 2)))
		return (scat,)
	def update(frame_index):
		f = valid_frames[frame_index]
		pts = np.column_stack([lon[f, :], lat[f, :]])
		scat.set_offsets(pts)
		ax.set_title(f"t = {elapsed_hours[f]:.1f} h, n = {np.isfinite(pts[:,0]).sum()}")
		return (scat,)
	anim = animation.FuncAnimation(fig, update, init_func=init, frames=len(valid_frames), blit=True, interval=100)
	out_path.parent.mkdir(parents=True, exist_ok=True)
	try:
		anim.save(out_path, fps=12, dpi=150)
		logging.info("Animation written: %s", out_path)
	except Exception as e:  # noqa: BLE001
		logging.warning("Animation failed: %s", e)
	plt.close(fig)


