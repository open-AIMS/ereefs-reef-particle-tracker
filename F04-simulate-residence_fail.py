def polygon_to_mask_field(fs, polygon: Polygon, name: str = "ReefMask"):  # type: ignore[no-untyped-def]
	"""Create a binary mask Field (1 inside polygon, 0 outside) on FieldSet grid.

	Uses shapely.vectorized.contains when available for speed; otherwise
	falls back to prepared geometry point iteration.
	"""
	try:
		from parcels import Field  # type: ignore
	except ImportError:  # pragma: no cover
		raise
	lon = fs.U.grid.lon
	lat = fs.U.grid.lat
	# Attempt fast vectorized path
	mask_bool: np.ndarray
	try:
		# Preferred in shapely >=2
		from shapely import contains_xy  # type: ignore
		mask_bool = contains_xy(polygon, lon, lat)
	except Exception:  # noqa: BLE001
		# Try deprecated vectorized.contains
		try:  # pragma: no cover
			from shapely import vectorized  # type: ignore
			mask_bool = vectorized.contains(polygon, lon, lat)
		except Exception:
			# Fallback: prepared geometry loop (slower)
			try:
				from shapely.prepared import prep  # type: ignore
				P = prep(polygon)
			except Exception:  # noqa: BLE001
				P = polygon  # type: ignore
			mask_bool = np.zeros(lon.shape, dtype=bool)
			for j in range(lon.shape[0]):
				for i in range(lon.shape[1]):
					if P.contains(Point(float(lon[j, i]), float(lat[j, i]))):
						mask_bool[j, i] = True
	mesh_arg = getattr(getattr(fs.U, "grid", None), "mesh", "spherical")
	mask = mask_bool.astype(np.float32)
	field = Field(name=name, data=mask, lon=lon, lat=lat, mesh=mesh_arg)
	fs.add_field(field)
	return field


def add_domain_mask(fs, shrink: int, name: str = "DomainMask"):  # type: ignore[no-untyped-def]
	"""Add a DomainMask field with zeros on shrunken outer rim.

	Parameters
	----------
	fs : FieldSet
	shrink : int
		Number of outer cells (per side) to flag as 0 (excluded). 0 keeps all ones.
	name : str
		Field name.
	"""
	if shrink < 0:
		raise ValueError("shrink must be >= 0")
	try:
		from parcels import Field  # type: ignore
	except ImportError:  # pragma: no cover
		raise
	lon = fs.U.grid.lon
	shape = lon.shape
	mask = np.ones(shape, dtype=np.float32)
	if shrink > 0:
		mask[:shrink, :] = 0
		mask[-shrink:, :] = 0
		mask[:, :shrink] = 0
		mask[:, -shrink:] = 0
	mesh_arg = getattr(getattr(fs.U, "grid", None), "mesh", "spherical")
	field = Field(name=name, data=mask, lon=lon, lat=fs.U.grid.lat, mesh=mesh_arg)
	fs.add_field(field)
	return field


def sample_points_in_polygon(polygon: Polygon | MultiPolygon, n: int, seed: int | None = None) -> Tuple[np.ndarray, np.ndarray]:
	"""Uniformly sample n points inside (Multi)Polygon via rejection sampling.

	Uses simple bbox rejection. For complex geometries a more advanced spatial
	sampling could be substituted later.
	"""
	if isinstance(polygon, MultiPolygon):  # unify to single geometry
		polygon = unary_union(polygon)
	from shapely.prepared import prep  # type: ignore
	prepared = prep(polygon)
	rng = np.random.default_rng(seed)
	minx, miny, maxx, maxy = polygon.bounds
	lons: list[float] = []
	lats: list[float] = []
	tries = 0
	max_tries = n * 100
	while len(lons) < n and tries < max_tries:
		tries += 1
		x = rng.uniform(minx, maxx)
		y = rng.uniform(miny, maxy)
		if prepared.contains(Point(float(x), float(y))):
			lons.append(x)
			lats.append(y)
	if len(lons) < n:
		raise RuntimeError(f"Could not sample {n} points inside polygon after {tries} tries")
	return np.array(lons, dtype=np.float32), np.array(lats, dtype=np.float32)


