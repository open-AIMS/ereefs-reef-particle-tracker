def _install_particle_kernels():  # type: ignore[no-untyped-def]
	try:
		from parcels import JITParticle, Variable  # type: ignore
	except ImportError:  # pragma: no cover
		return None

	class ReefParticle(JITParticle):  # type: ignore
		inside = Variable('inside', dtype=np.int32, initial=0)  # 1 if inside reef mask at sample time
		active = Variable('active', dtype=np.int32, initial=1)  # 1 while not deleted by domain mask

	def SampleInside(particle, fieldset, time):  # type: ignore[no-untyped-def]
		# Sample reef and domain masks; inside only if reef==1 and active domain.
		# Avoid bare return (older Parcels JIT had issues when compiling kernels with bare return statements).
		reef = fieldset.ReefMask[time, particle.depth, particle.lat, particle.lon]
		domain = fieldset.DomainMask[time, particle.depth, particle.lat, particle.lon]
		if domain < 0.5:
			particle.active = 0
			particle.delete()
		else:
			if reef >= 0.5:
				particle.inside = 1
			else:
				particle.inside = 0

	return ReefParticle, SampleInside


